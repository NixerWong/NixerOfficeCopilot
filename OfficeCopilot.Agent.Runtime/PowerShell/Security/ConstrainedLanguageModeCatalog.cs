        /// <summary>
        /// Check if a type literal is in the CLM allowlist.
        /// </summary>
        public static bool IsAllowed(string typeName)
        {
            if (string.IsNullOrWhiteSpace(typeName)) return true;
            return AllowedTypes.Contains(typeName.ToLowerInvariant().Trim());
        }
